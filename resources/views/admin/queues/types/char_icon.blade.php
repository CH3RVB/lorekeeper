<h3>Character Icon</h3>
<p>This will enable a queue for character icon submissions and processing. Upon approval, the chosen characters' masterlist icons will be updated immediately.</p>
<p>There are no admin settings to adjust here, but the user-end queue will allow for the selection of an image, as well as an artist credit field.</p>
<p>If you wish for the submission to consume items, then simply turn on "item_consume" to true in the queue_types config.</p>
